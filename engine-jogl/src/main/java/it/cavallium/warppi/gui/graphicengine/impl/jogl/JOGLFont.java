package it.cavallium.warppi.gui.graphicengine.impl.jogl;

import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.util.function.Function;

import com.jogamp.common.nio.Buffers;
import com.jogamp.opengl.GL;
import com.jogamp.opengl.util.texture.Texture;
import com.jogamp.opengl.util.texture.TextureData;

import it.cavallium.warppi.device.display.DisplayOutputDevice;
import it.cavallium.warppi.gui.graphicengine.BinaryFont;
import it.cavallium.warppi.gui.graphicengine.impl.common.RFTFont;

public class JOGLFont implements BinaryFont {

	public Texture texture;
	public int textureW;
	public int textureH;
	public int charW;
	public int charH;
	public int minCharIndex;
	public int maxCharIndex;
	public int[] intervals;
	public int intervalsTotalSize = 0;
	public int memoryWidth;
	public int memoryHeight;
	public int memoryWidthOfEachColumn;

	private boolean initialized = false;
	private byte[] alphaPixels;
	private final boolean allowRuntimeAtlasGeneration;

	JOGLFont(final String name) throws IOException {
		this(name, true);
	}

	JOGLFont(final String name, final boolean allowRuntimeAtlasGeneration) throws IOException {
		this.allowRuntimeAtlasGeneration = allowRuntimeAtlasGeneration;
		load(name);
	}

	public JOGLFont(final String path, final String name) throws IOException {
		allowRuntimeAtlasGeneration = true;
		load(path, name);
	}

	@Override
	public void load(final String name) throws IOException {
		load(null, name);
	}

	public void load(final String path, final String name) throws IOException {
		final JOGLFontAtlas atlas;
		if (path == null) {
			atlas = loadAtlas(name, allowRuntimeAtlasGeneration, JOGLFont.class::getResourceAsStream);
		} else {
			// External fonts cannot be generated by Maven; convert them directly in memory.
			atlas = JOGLFontAtlas.fromRftFont(RFTFont.loadTemporaryFont(path, name));
		}
		load(atlas);
	}

	static JOGLFontAtlas loadAtlas(final String name, final boolean allowRuntimeAtlasGeneration,
			final Function<String, InputStream> resourceLoader) throws IOException {
		final String rftResource = "/font_" + name + ".rft";
		if (allowRuntimeAtlasGeneration) {
			try (InputStream input = resourceLoader.apply(rftResource)) {
				if (input != null) {
					final JOGLFontAtlas atlas = JOGLFontAtlas.fromRft(input);
					System.out.println("[font-atlas] Built in memory from " + rftResource);
					return atlas;
				}
			}
		}

		final String atlasResource = "/font-atlas/font_" + name + ".wfa";
		try (InputStream input = resourceLoader.apply(atlasResource)) {
			if (input != null)
				return JOGLFontAtlas.read(input);
		}
		if (allowRuntimeAtlasGeneration)
			throw new IOException("Missing source font " + rftResource
					+ " and generated JOGL font atlas " + atlasResource);
		throw new IOException("Missing generated JOGL font atlas " + atlasResource
				+ "; build the engine-jogl module with Maven");
	}

	private void load(final JOGLFontAtlas atlas) {
		charW = atlas.charW;
		charH = atlas.charH;
		minCharIndex = atlas.minCharIndex;
		maxCharIndex = atlas.maxCharIndex;
		intervals = atlas.intervals;
		intervalsTotalSize = 0;
		for (int i = 2; i < intervals.length; i += 3)
			intervalsTotalSize += intervals[i];
		memoryWidth = atlas.textureW;
		memoryHeight = atlas.textureH;
		memoryWidthOfEachColumn = atlas.columns;
		textureW = atlas.textureW;
		textureH = atlas.textureH;
		alphaPixels = atlas.alphaPixels;
	}

	public int[] getCharIndexes(final String txt) {
		final int[] indexes = new int[txt.length()];
		for (int i = 0; i < txt.length(); i++)
			indexes[i] = getCharIndex(txt.charAt(i));
		return indexes;
	}

	public int getCharIndex(final char c) {
		final int originalIndex = (c & 0xFFFF) - minCharIndex;
		return compressIndex(originalIndex);
	}

	private int compressIndex(final int originalIndex) {
		int compressedIndex = 0;
		for (int i = 0; i < intervals.length; i += 3)
			if (intervals[i] > originalIndex)
				break;
			else if (originalIndex <= intervals[i + 1]) {
				compressedIndex += originalIndex - intervals[i];
				break;
			} else
				compressedIndex += intervals[i + 2];
		return compressedIndex;
	}

	@SuppressWarnings("unused")
	private int decompressIndex(final int compressedIndex) {
		final int originalIndex = 0;
		int i = 0;
		for (final int intvl = 0; i < intervals.length; i += 3) {
			i += intervals[intvl + 2];
			if (i >= compressedIndex)
				return intervals[intvl + 1] - (i - compressedIndex);
		}
		return originalIndex;
	}

	private void genTexture() {
		if (alphaPixels == null)
			throw new IllegalStateException("Font atlas pixels are no longer available");
		final ByteBuffer pixels = Buffers.newDirectByteBuffer(alphaPixels.length);
		pixels.put(alphaPixels).rewind();
		final TextureData data = new TextureData(JOGLRenderer.gl.getGLProfile(), GL.GL_ALPHA, textureW, textureH,
				0, GL.GL_ALPHA, GL.GL_UNSIGNED_BYTE, false, false, false, pixels, null);
		try {
			texture = new Texture(JOGLRenderer.gl, data);
			texture.setTexParameteri(JOGLRenderer.gl, GL.GL_TEXTURE_MIN_FILTER, GL.GL_NEAREST);
			texture.setTexParameteri(JOGLRenderer.gl, GL.GL_TEXTURE_MAG_FILTER, GL.GL_NEAREST);
			alphaPixels = null;
		} finally {
			data.flush();
		}
	}

	@Override
	public void initialize(final DisplayOutputDevice d) {
		if (initialized)
			return;
		genTexture();
		initialized = true;
	}

	@Override
	public void use(final DisplayOutputDevice d) {
		if (!initialized)
			initialize(d);
		final JOGLRenderer r = (JOGLRenderer) d.getGraphicEngine().getRenderer();
		r.currentFont = this;
		r.useTexture(texture, textureW, textureH);
	}

	@Override
	public int getStringWidth(final String text) {
		final int w = charW * text.length();
		if (text.length() > 0)
			return w;
		else
			return 0;
	}

	@Override
	public int getCharacterWidth() {
		return charW;
	}

	@Override
	public int getCharacterHeight() {
		return charH;
	}

	@Override
	public boolean isInitialized() {
		return initialized;
	}

	@Override
	public int getSkinWidth() {
		return memoryWidth;
	}

	@Override
	public int getSkinHeight() {
		return memoryHeight;
	}
}
